import { test, expect } from './fixtures'

test('create, rename, search, delete and undo a board', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Aucune carte')).toBeVisible()
  await page.getByRole('button', { name: 'Nouvelle carte' }).click()
  await expect(page).toHaveURL(/\/b\/[0-9a-f-]{36}$/)
  await page.getByRole('link', { name: '← Cartes' }).click()
  await page.getByTestId('board').filter({ hasText: 'Sans titre' }).hover()
  await page.getByRole('button', { name: 'Actions pour Sans titre' }).click()
  await page.getByRole('menuitem', { name: 'Renommer' }).click()
  await page.getByRole('textbox', { name: 'Nom de la carte' }).fill('Hépatite B')
  await page.keyboard.press('Enter')
  const search = page.getByPlaceholder('Rechercher une carte…')
  await search.fill('hepatite')
  await expect(page.getByTestId('board').filter({ hasText: 'Hépatite B' })).toBeVisible()
  await expect(page.locator('mark')).toHaveText('Hépatite')
  await search.fill('cardio')
  await expect(page.getByText('Aucune carte')).toBeVisible()
  await search.fill('')
  await page.getByTestId('board').filter({ hasText: 'Hépatite B' }).hover()
  await page.getByRole('button', { name: 'Actions pour Hépatite B' }).click()
  await page.getByRole('menuitem', { name: 'Supprimer' }).click()
  await expect(page.getByText('Aucune carte')).toBeVisible()
  await expect(page.getByRole('status')).toContainText('« Hépatite B » supprimée')
  await page.getByRole('button', { name: 'Annuler' }).click()
  await expect(page.getByTestId('board').filter({ hasText: 'Hépatite B' })).toBeVisible()
})

test('keyboard: N creates, / searches, ↓ then Enter opens', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Nouvelle carte' })).toBeVisible() // list ready (session checked)
  for (const name of ['Cardiologie', 'Néphrologie']) {
    await page.keyboard.press('n')
    const title = page.getByRole('textbox', { name: 'Nom de la carte' })
    await expect(title).toBeFocused()
    await page.keyboard.type(name)
    await page.keyboard.press('Enter')
    await page.getByRole('link', { name: '← Cartes' }).click()
  }
  await expect(page.getByTestId('board')).toHaveText([/Néphrologie/, /Cardiologie/])
  await page.keyboard.press('/')
  await expect(page.getByPlaceholder('Rechercher une carte…')).toBeFocused()
  await page.keyboard.press('Escape')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('textbox', { name: 'Nom de la carte' })).toHaveValue('Cardiologie')
})

test('an unknown or deleted board shows "Carte introuvable" instead of a canvas', async ({ page }) => {
  await page.goto('/b/00000000-0000-4000-8000-000000000000')
  await expect(page.getByText('Carte introuvable')).toBeVisible()
  await expect(page.locator('.react-flow__pane')).toHaveCount(0)
  await page.goto('/')
  await page.getByRole('button', { name: 'Nouvelle carte' }).click()
  await expect(page).toHaveURL(/\/b\/[0-9a-f-]{36}$/)
  await page.getByRole('link', { name: '← Cartes' }).click()
  await page.getByTestId('board').filter({ hasText: 'Sans titre' }).hover()
  await page.getByRole('button', { name: 'Actions pour Sans titre' }).click()
  await page.getByRole('menuitem', { name: 'Supprimer' }).click()
  await expect(page.getByText('Aucune carte')).toBeVisible()
  await page.goBack()
  await expect(page.getByText('Carte introuvable')).toBeVisible()
  await expect(page.locator('.react-flow__pane')).toHaveCount(0)
})

test('a new board opens with its title selected, ready to type', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Nouvelle carte' }).click()
  const title = page.getByRole('textbox', { name: 'Nom de la carte' })
  await expect(title).toBeFocused()
  await expect(title).toHaveValue('Sans titre')
  await page.keyboard.type('Cardiologie')
  await page.locator('.react-flow__pane').click({ position: { x: 300, y: 300 } })
  await expect(title).toHaveValue('Cardiologie')
  await page.getByRole('link', { name: '← Cartes' }).click()
  await expect(page.getByTestId('board').filter({ hasText: 'Cardiologie' })).toBeVisible()
})
